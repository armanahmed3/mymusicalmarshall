
/**
 * Utility to clean song titles for front site display (removes underscores and dashes)
 */
export function cleanSongTitle(title?: string): string {
  if (!title) return '';
  return title
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

